#!/usr/bin/env python3
"""Generate src/diacritics.rs from Diacritical.Net, the library Sonarr's RemoveDiacritics uses.

Sources:
* Diacritical.Net 1.0.5 (https://github.com/anth12/diacritical-dotnet, MIT), the commit recorded
  in the NuGet package metadata: Diacritical/DefaultDiacriticProvider.cs;
* Sonarr's AdditionalDiacriticsProvider (registered after the default provider, so its entries
  win), which this script lists inline.

Development tool only; Kitsunarr itself never runs Python.

usage: python3 -I gen_diacritics.py <diacritical-dotnet checkout> <output.rs>
"""
import re
import sys

COMMIT = "476b8303a8e1dd110d2627e5bddd5b8a60111513"
SONARR_ADDITIONS = {"ð": "d", "Ð": "D", "þ": "th"}

checkout, out = sys.argv[1], sys.argv[2]
src = open(f"{checkout}/Diacritical/DefaultDiacriticProvider.cs", encoding="utf-8-sig").read()
pairs = re.findall(r"\{'((?:\\.|[^'\\])+)',\s*\"((?:\\.|[^\"\\])*)\"\}", src)
table = {}
for key, value in pairs:
    assert len(key) == 1 and "\\" not in value, (key, value)
    table[key] = value
table.update(SONARR_ADDITIONS)

def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def rust_char(c):
    return "'\\''" if c == "'" else f"'\\u{{{ord(c):04X}}}'"

lines = [
    "//! Diacritic → ASCII table used by `remove_diacritics` (generated, do not edit).",
    "//!",
    f"//! Generated by `tools/gen_diacritics.py` from Diacritical.Net 1.0.5 (commit {COMMIT[:9]},",
    "//! https://github.com/anth12/diacritical-dotnet, MIT License, Copyright (c) 2019 Anthony",
    "//! Halliday), plus Sonarr's `AdditionalDiacriticsProvider` (ð → d, Ð → D, þ → th).",
    "",
    "/// Sorted by character for binary search.",
    "pub(crate) const TABLE: &[(char, &str)] = &[",
]
for key in sorted(table, key=ord):
    lines.append(f"    ({rust_char(key)}, {rust_str(table[key])}), // {key}")
lines.append("];")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(table)} entries written to {out}")
