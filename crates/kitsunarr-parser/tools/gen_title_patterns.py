#!/usr/bin/env python3
"""Generate src/title_patterns.rs from Sonarr's Parser.cs.

Every `Regex` / `RegexReplace` field of `NzbDrone.Core/Parser/Parser.cs` is copied verbatim
(C# verbatim strings decoded: `""` → `"`), with its IgnoreCase option. Commented-out patterns
are skipped, as they are upstream. The patterns are run by `netregex`, which implements .NET
semantics, so no rewriting is needed.

Development tool only; Kitsunarr itself never runs Python.

usage: python3 -I gen_title_patterns.py <Parser.cs> <revision> <output.rs>
"""
import re
import sys

src_path, revision, out = sys.argv[1], sys.argv[2], sys.argv[3]
lines = open(src_path, encoding="utf-8-sig").read().splitlines()
# Drop commented-out lines entirely (upstream keeps disabled patterns as comments).
code = "\n".join("" if l.lstrip().startswith("//") and "new Regex" in l else l for l in lines)

FIELD = re.compile(r"private static readonly (?:Regex|RegexReplace)(?:\[\])?\s+(\w+)\s*=\s*(?=new)")
CALL = re.compile(r"new(?:\s+Regex|\s+RegexReplace)?\s*\(\s*@\"")


def verbatim(s, i):
    """Decodes a C# verbatim string starting after `@"`; returns (value, index after)."""
    out = []
    while True:
        c = s[i]
        if c == '"':
            if s[i + 1:i + 2] == '"':
                out.append('"')
                i += 2
                continue
            return "".join(out), i + 1
        out.append(c)
        i += 1


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


fields = []
for m in FIELD.finditer(code):
    name = m.group(1)
    end = code.find(";", m.end())
    # A field ends at the first ';' outside a string; scan string-aware.
    i, depth = m.end(), 0
    entries = []
    while True:
        call = CALL.search(code, i)
        semi = i
        # find the field terminator ';' that is not inside a string literal
        j = i
        in_str = False
        while j < len(code):
            if not in_str and code.startswith('@"', j):
                _, j = verbatim(code, j + 2)
                continue
            if not in_str and code[j] == '"':
                in_str = True
            elif in_str and code[j] == '"' and code[j - 1] != "\\":
                in_str = False
            elif not in_str and code[j] == ";":
                break
            j += 1
        terminator = j
        if not call or call.start() > terminator:
            break
        pattern, k = verbatim(code, call.end())
        close = k
        paren = 1
        # options run to the matching ')' of this call
        while paren and close < len(code):
            if code.startswith('@"', close):
                _, close = verbatim(code, close + 2)
                continue
            if code[close] == "(":
                paren += 1
            elif code[close] == ")":
                paren -= 1
            close += 1
        args = code[k:close]
        ignore_case = "IgnoreCase" in args
        # Comment immediately preceding the call (array entries).
        before = code[:call.start()].rstrip().splitlines()
        comment = ""
        for prev in reversed(before):
            p = prev.strip()
            if p.startswith("//"):
                comment = p.lstrip("/ ").strip() + (" " + comment if comment else "")
                continue
            break
        entries.append((comment, pattern, ignore_case))
        i = close
    fields.append((name, entries))


def raw(s):
    hashes = "#"
    while f'"{hashes}' in s:
        hashes += "#"
    return f'r{hashes}"{s}"{hashes}'


out_lines = [
    "//! Regular expressions of Sonarr's `Parser.cs` (generated, do not edit).",
    "//!",
    f"//! Generated by `tools/gen_title_patterns.py` from Sonarr `src/NzbDrone.Core/Parser/Parser.cs`",
    f"//! at `{revision}` (GPL-3.0-or-later). Patterns are verbatim; they run on `netregex`.",
    "",
    "pub(crate) struct Pattern {",
    "    pub comment: &'static str,",
    "    pub pattern: &'static str,",
    "    pub ignore_case: bool,",
    "}",
    "",
]
total = 0
for name, entries in fields:
    total += len(entries)
    out_lines.append(f"/// `{name}`")
    out_lines.append(f"pub(crate) const {snake(name)}: &[Pattern] = &[")
    for comment, pattern, ic in entries:
        out_lines.append("    Pattern {")
        out_lines.append(f"        comment: {raw(comment)},")
        out_lines.append(f"        pattern: {raw(pattern)},")
        out_lines.append(f"        ignore_case: {'true' if ic else 'false'},")
        out_lines.append("    },")
    out_lines.append("];")
    out_lines.append("")
open(out, "w", encoding="utf-8").write("\n".join(out_lines))
print(f"{len(fields)} fields, {total} patterns")
for name, entries in fields:
    print(f"  {name}: {len(entries)}")
